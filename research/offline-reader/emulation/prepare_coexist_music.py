"""Generate an original four-second arpeggio WAV in flash for mixer testing."""
from pathlib import Path
import io, math, struct, wave
def prepare(root):
    rate=22050
    samples=[]
    notes=(220,277.1826,329.6276,440,329.6276,277.1826,246.9417,329.6276)
    for i in range(rate*4):
        t=i/rate; local=t%0.5
        envelope=min(1,local/.02)*max(0,1-local/.5)
        f=notes[int(t/.5)]
        samples.append(int(9000*envelope*(math.sin(2*math.pi*f*t)+.25*math.sin(4*math.pi*f*t))/1.25))
    stream=io.BytesIO()
    with wave.open(stream,'wb') as out:
        out.setnchannels(1);out.setsampwidth(2);out.setframerate(rate)
        out.writeframes(struct.pack('<'+'h'*len(samples),*samples))
    data=stream.getvalue();target=Path(root)/'generated/coexist_music.h'
    target.write_text('// Original diagnostic arpeggio, generated by prepare_coexist_music.py\n#pragma once\n#include <stdint.h>\nstatic const uint8_t coexistMusic[] = {\n'+
        '\n'.join(','.join(str(b) for b in data[i:i+24])+',' for i in range(0,len(data),24))+'\n};\n')
    return len(data)
if __name__=='__main__':print(prepare(Path(__file__).resolve().parents[1]))
